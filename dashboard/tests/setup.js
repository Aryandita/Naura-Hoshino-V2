// Suppress console warnings during tests
const originalWarn = console.warn;
console.warn = (...args) => {
  // Filter out known warnings
  if (args[0]?.includes?.('Unknown theme') || args[0]?.includes?.('Unknown density')) {
    return;
  }
  originalWarn.apply(console, args);
};
