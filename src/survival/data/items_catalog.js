const TIERS = Object.freeze({
  COMMON: { tier: 1, rarity: "Common", color: "#9CA3AF", badge: "I" },
  UNCOMMON: { tier: 2, rarity: "Uncommon", color: "#86EFAC", badge: "II" },
  RARE: { tier: 3, rarity: "Rare", color: "#93C5FD", badge: "III" },
  EPIC: { tier: 4, rarity: "Epic", color: "#C084FC", badge: "IV" },
  LEGENDARY: { tier: 5, rarity: "Legendary", color: "#FFD700", badge: "V" },
});

function makeItem({
  id,
  name,
  description,
  price,
  category,
  tierKey,
  emoji,
  iconType,
  attributes = {},
}) {
  const tierInfo = TIERS[tierKey] || TIERS.COMMON;
  const sellPrice = Math.max(1, Math.floor(price * 0.5));
  return Object.freeze({
    id,
    name,
    description,
    price,
    sellPrice,
    category,
    tier: tierInfo.tier,
    rarity: tierInfo.rarity,
    tierColor: tierInfo.color,
    badge: tierInfo.badge,
    emoji: emoji || "📦",
    iconType: iconType || category,
    image: `/items/${id}.svg`,
    ...attributes,
  });
}

